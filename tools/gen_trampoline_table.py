"""The pre-linker's cross-module trampolines as a table for the 3DS build, instead of 28,000 translated functions.

Brawl's modules are pre-linked at homes far apart, so a call from one module into another goes through a veneer
(lis r12 / addi r12 / mtctr r12 / bctr) the pre-linker placed at an address of its own. The translator made each a
function (`r12 = hi; r12 = (r12 + lo); ctr = r12; InvokeIndirectJump(ctr, ctx)`), but their bytes are not in guest
memory: a build that leaves most functions out (select_translated_code.py) and interprets them cannot run a veneer
from memory, and keeping all 28,026 translated costs ~2 MB of code the 3DS does not have.

This tool
  * writes <out.cpp>: every veneer's (address, target), sorted, for Brawl3dsTrampolineTarget (main_3ds.cpp looks an
    unlinked function up there before handing it to the interpreter);
  * makes every veneer in the selection a stub (they all resolve through the table: one path, a few dozen cycles
    more than the translated veneer, which made the same dispatch call).

Usage: python -I tools/gen_trampoline_table.py <full shards dir> <selection dir> <out.cpp>
Only shards that change are rewritten.
"""
import re
import sys
from pathlib import Path

MARKER = re.compile(r'^#line 1 "func_([0-9A-F]{8})\.cpp"$', re.M)
CLOSING = "#undef MKW_STATIC_TRANSLATED_CALL"
STUB = ('#line 1 "func_{a}.cpp"\n'
        'extern "C" void Brawl3ds_NotLinked(uint32_t guestAddress, CpuContext* ctx);\n'
        'extern "C" void func_{a}(CpuContext* MKW_RESTRICT ctx) {{ Brawl3ds_NotLinked(0x{a}u, ctx); }}\n\n')
VENEER = re.compile(r"\{\n    r12 = (-?\d+);\n    r12 = \(r12 \+ (-?\d+)\);\n    ctr = r12;\n    ctx->gpr\[12\] = r12;\n"
                    r"    ctx->ctr = ctr;\n    InvokeIndirectJump\(ctr, ctx\);")


def split(text):
    body = text.rstrip()
    assert body.endswith(CLOSING), "shard does not end with " + CLOSING
    body = body[: -len(CLOSING)]
    marks = list(MARKER.finditer(body))
    head = body[: marks[0].start()] if marks else body
    parts = []
    for i, mark in enumerate(marks):
        end = marks[i + 1].start() if i + 1 < len(marks) else len(body)
        parts.append((mark.group(1), body[mark.start(): end]))
    return head, parts


def veneer_target(text):
    if text.count("\n") > 30 or "MemoryInline::" in text:
        return None
    m = VENEER.search(text)
    return (int(m.group(1)) + int(m.group(2))) & 0xFFFFFFFF if m else None


def main():
    full_dir, selection, out = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
    table = {}
    for path in sorted(full_dir.glob("shard_*.cpp")):
        text = path.read_text(encoding="utf-8")
        if "InvokeIndirectJump(ctr, ctx);" not in text:
            continue
        for address, part in split(text)[1]:
            target = veneer_target(part)
            if target is not None:
                table[int(address, 16)] = target
    stubbed = changed = 0
    for path in sorted(selection.glob("shard_*.cpp")):
        text = path.read_text(encoding="utf-8")
        if "InvokeIndirectJump(ctr, ctx);" not in text:
            continue
        head, parts = split(text)
        out_parts = [head]
        touched = False
        for address, part in parts:
            if int(address, 16) in table and "Brawl3ds_NotLinked(0x" not in part:
                out_parts.append(STUB.format(a=address))
                stubbed += 1
                touched = True
            else:
                out_parts.append(part)
        if touched:
            out_parts.append(CLOSING + "\n")
            path.write_text("".join(out_parts), encoding="utf-8")
            changed += 1
    lines = ["// Generated by brawl3ds tools/gen_trampoline_table.py: the pre-linker's cross-module veneers,\n"
             "// (address, target) sorted by address. Do not edit.\n#include <cstdint>\n"
             f"extern \"C\" const uint32_t g_brawl3dsTrampolineCount = {len(table)};\n"
             "extern \"C\" const uint32_t g_brawl3dsTrampolines[][2] = {\n"]
    for address in sorted(table):
        lines.append(f"    {{0x{address:08X}u, 0x{table[address]:08X}u}},\n")
    lines.append("};\n")
    out.write_text("".join(lines), encoding="utf-8")
    print(f"{len(table)} veneers in the table ({out}); {stubbed} made stubs in {changed} selection shards")


if __name__ == "__main__":
    main()
