"""Write a binary file into a C++ source as a byte array (the 3DS build embeds its compiled PICA200 shaders).

  python -I tools/embed_binary.py <input> <symbol> <out.cpp>

Defines `extern "C" const unsigned char <symbol>[]` and `extern "C" const unsigned int <symbol>_size`. The output is
only rewritten when its contents change.
"""
import sys
from pathlib import Path


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    data = Path(sys.argv[1]).read_bytes()
    symbol, out = sys.argv[2], Path(sys.argv[3])
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    text = (f"// Generated by brawl3ds tools/embed_binary.py from {Path(sys.argv[1]).name}; do not edit.\n"
            f'extern "C" alignas(4) const unsigned char {symbol}[] = {{\n    ' + ",\n    ".join(rows) + "\n};\n"
            f'extern "C" const unsigned int {symbol}_size = {len(data)};\n')
    if not out.exists() or out.read_text(encoding="utf-8") != text:
        out.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
