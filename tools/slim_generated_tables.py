"""The translator's tables without their names, for the 3DS build's code budget.

Two tables carry a name for each of the game's ~120,000 functions, for crash reports and profiles only:
  * generated/guest_symbol_table.cpp (address -> symbol name): ~3.4 MiB in the executable;
  * build_shards/base_registration/*.cpp (kRecords: "func_XXXXXXXX" per record): ~1.7 MiB.
The 3DS has ~44.5 MiB for code and data together (more does not boot), and every MiB here is ~300 translated
functions that would otherwise run in the interpreter. Reports then show addresses: name them on the PC with
the decomp's symbols.txt.

Usage: python -I tools/slim_generated_tables.py <wiicompiled/generated> <out dir> [<selection dir>]
With a selection (the shards the build compiles), the records of the functions it holds only as stubs are left
out too: the runtime keeps ~120 bytes of heap per registered function in three containers (14 MiB for the whole
game, in small blocks that fragment the heap), and a stub needs none of it: indirect calls find it through the
generated dispatch table, which is separate.
Writes <out>/guest_symbol_table_3ds.cpp (an empty table) and <out>/registration/registration_*.cpp (the records
with a null name; the runtime reads a null name as ""). Unchanged outputs are not rewritten.
"""
import re
import sys
from pathlib import Path

EMPTY_TABLE = '''// Generated by brawl3ds tools/slim_generated_tables.py: the guest symbol table, left empty on the 3DS.
#include <cstdint>

extern "C" {
extern const uint32_t kGuestMapSymbolCount;
extern const uint32_t kGuestMapSymbolAddresses[];
extern const char* const kGuestMapSymbolNames[];
const uint32_t kGuestMapSymbolCount = 0u;
const uint32_t kGuestMapSymbolAddresses[] = {0u};
const char* const kGuestMapSymbolNames[] = {""};
}
'''
NAME = re.compile(r'(\{0x[0-9A-F]{8}u, )"func_[0-9A-F]{8}"(, &func_)')
RECORD = re.compile(r'^    \{0x([0-9A-F]{8})u, nullptr, &func_[0-9A-F]{8}, .*\},\r?\n', re.M)
MARKER = re.compile(r'^#line 1 "func_([0-9A-F]{8})\.cpp"$', re.M)


def write_if_changed(path, text):
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return False
    path.write_text(text, encoding="utf-8")
    return True


def main():
    generated, out = Path(sys.argv[1]), Path(sys.argv[2])
    (out / "registration").mkdir(parents=True, exist_ok=True)
    changed = write_if_changed(out / "guest_symbol_table_3ds.cpp", EMPTY_TABLE)
    records = dropped = 0
    stubs = set()
    if len(sys.argv) > 3:
        for shard in sorted(Path(sys.argv[3]).glob("shard_*.cpp")):
            text = shard.read_text(encoding="utf-8")
            for mark in MARKER.finditer(text):
                if f"Brawl3ds_NotLinked(0x{mark.group(1)}u" in text[mark.end(): mark.end() + 400]:
                    stubs.add(mark.group(1))
    for path in sorted((generated / "build_shards" / "base_registration").glob("*.cpp")):
        text, n = NAME.subn(r"\1nullptr\2", path.read_text(encoding="utf-8"))
        records += n
        if stubs:
            kept = []
            last = 0
            for m in RECORD.finditer(text):
                if m.group(1) in stubs:
                    kept.append(text[last: m.start()])
                    last = m.end()
                    dropped += 1
            text = "".join(kept) + text[last:]
        changed |= write_if_changed(out / "registration" / path.name, text)
    print(f"{records} records without a name, {dropped} left out (stubs); outputs {'written' if changed else 'unchanged'} in {out}")


if __name__ == "__main__":
    main()
